document.addEventListener("DOMContentLoaded", function() {
    const select = document.getElementById("frequent_select");
    const rows = document.querySelectorAll(".FrequentQA_content_row");

    // Hide all rows initially
    rows.forEach(row => row.style.display = "none");

    // Show the first option by default
    const firstValue = select.value.toLowerCase();
    rows.forEach(row => {
        if (row.querySelector("h5").textContent.toLowerCase() === firstValue) {
            row.style.display = "block";
        }
    });

    // Listen for changes
    select.addEventListener("change", function() {
        const selectedValue = this.value.toLowerCase();

        rows.forEach(row => {
            const heading = row.querySelector("h5").textContent.toLowerCase();
            if (heading === selectedValue) {
                row.style.display = "block";
            } else {
                row.style.display = "none";
            }
        });
    });
});
